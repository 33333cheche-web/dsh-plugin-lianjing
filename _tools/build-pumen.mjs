let cursor = 0;
PARTS.forEach((part, index) => {
  if (part.start !== cursor) throw new Error(`分段不连续：第 ${index + 1} 段期望起始行 ${cursor}，实为 ${part.start}`);
  corpus.segments.push({
    no: index + 1,
    label: part.label,
    text: body.slice(part.start, part.end + 1).join('').replace(/\s+/g, ''),
    gist: part.gist,
    terms: part.terms.map(([word, gloss]) => ({ word, gloss })),
    practice: part.practice,
  });
  cursor = part.end + 1;
});
if (cursor !== body.length) throw new Error(`未覆盖全部原文：用了 ${cursor} 行，共 ${body.length} 行`);

writeFileSync(OUT, JSON.stringify(corpus, null, 2) + '\n', 'utf8');
console.log(`写入 ${OUT}：${corpus.segments.length} 段，正文 ${corpus.segments.reduce((n, s) => n + s.text.length, 0)} 字`);
